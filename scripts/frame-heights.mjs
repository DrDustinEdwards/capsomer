// Measures every example frame on the built site at four page widths and writes site/frame-heights.json (frame key
// to heights) and site/frame-heights.css (the heights as custom properties on data-h1 to data-h4), so a component
// page reserves each frame's final height and does not shift as the frame loads (CLS). Run after `npm run site`,
// commit both files, then rebuild:  node scripts/frame-heights.mjs
import { createServer } from "node:http";
import { createReadStream, existsSync, statSync, writeFileSync } from "node:fs";
import { extname, join, resolve } from "node:path";
import { chromium } from "playwright";

const root = resolve(import.meta.dirname, "..");
const dist = join(root, "site-dist");
const WIDTHS = [390, 768, 1100, 1440];
const types = {
  ".html": "text/html",
  ".css": "text/css",
  ".js": "text/javascript",
  ".json": "application/json",
  ".svg": "image/svg+xml",
  ".woff2": "font/woff2",
};
const server = createServer((req, res) => {
  let file = join(dist, decodeURIComponent(req.url.split("?")[0]));
  if (existsSync(file) && statSync(file).isDirectory()) file = join(file, "index.html");
  if (!existsSync(file) && existsSync(`${file}.html`)) file += ".html";
  if (!existsSync(file)) return res.writeHead(404).end("not found");
  res.writeHead(200, { "content-type": types[extname(file)] ?? "application/octet-stream" });
  createReadStream(file).pipe(res);
}).listen(0);
const base = `http://localhost:${server.address().port}`;
const names = (await import("node:fs"))
  .readdirSync(join(dist, "components"), { withFileTypes: true })
  .filter((d) => d.isDirectory())
  .map((d) => d.name);

const browser = await chromium.launch();
const heights = {};
for (const [i, width] of WIDTHS.entries()) {
  const page = await browser.newPage({ viewport: { width, height: 900 } });
  for (const name of names) {
    await page.goto(`${base}/components/${name}/`, { waitUntil: "load" });
    // Frames are lazy: bring each in, then wait for its script-set height to settle.
    await page.evaluate(async () => {
      for (const f of document.querySelectorAll(".comp-ex-frame")) {
        f.loading = "eager";
        f.scrollIntoView();
        await new Promise((r) => setTimeout(r, 50));
      }
    });
    await page.waitForFunction(
      () =>
        [...document.querySelectorAll(".comp-ex-frame")].every(
          (f) =>
            f.contentDocument?.readyState === "complete" && f.contentDocument.URL !== "about:blank",
        ),
      null,
      { timeout: 15000 },
    );
    await page.waitForTimeout(600);
    const got = await page.evaluate(() =>
      [...document.querySelectorAll(".comp-ex-frame")].map((f) => [
        f.dataset.fk,
        Math.round(f.getBoundingClientRect().height),
      ]),
    );
    for (const [key, h] of got) (heights[key] ??= [])[i] = h;
  }
  await page.close();
}
await browser.close();
server.close();

const sorted = Object.fromEntries(Object.entries(heights).sort(([a], [b]) => a.localeCompare(b)));
writeFileSync(
  join(root, "site/frame-heights.json"),
  `${JSON.stringify(sorted, null, 1).replace(/\[\n\s+(\d+),\n\s+(\d+),\n\s+(\d+),\n\s+(\d+)\n\s+\]/g, "[$1, $2, $3, $4]")}\n`,
);
const rules = WIDTHS.flatMap((_, i) =>
  [...new Set(Object.values(sorted).map((h) => h[i]))]
    .sort((a, b) => a - b)
    .map((v) => `.comp-ex-frame[data-h${i + 1}="${v}"] { --fh${i + 1}: ${v}px; }`),
);
writeFileSync(
  join(root, "site/frame-heights.css"),
  `/* Generated by scripts/frame-heights.mjs: each example frame's measured height at four page widths. */\n${rules.join("\n")}\n`,
);
console.log(`frame-heights: ${Object.keys(sorted).length} frames, ${rules.length} rules`);
