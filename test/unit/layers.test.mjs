import { strict as assert } from "node:assert";
import { readFileSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";

// Every Capsomer stylesheet fixes the layer order itself. A bundler may emit one component's
// CSS before css/layers.css; if that file did not state the order, its own layer would come
// first and base.css's `button { color: inherit }` would beat the component (found when a
// primary button painted dark text on its accent fill).
const ORDER = "@layer cap.reset, cap.tokens, cap.base, cap.components, cap.utilities;";

function cssFiles(dir) {
  return readdirSync(dir, { withFileTypes: true }).flatMap((e) => {
    const p = join(dir, e.name);
    if (e.isDirectory()) return e.name === "specimen" ? [] : cssFiles(p);
    // states.css is the states page's own, generated by bin/states.mjs, not a component's.
    return e.name.endsWith(".css") && e.name !== "states.css" ? [p] : [];
  });
}

test("every component and base stylesheet states the layer order", () => {
  const files = [...cssFiles("components"), "css/base.css", "css/utilities.css", "css/prose.css"];
  assert.ok(files.length > 20);
  const bad = files.filter((f) => !readFileSync(f, "utf8").includes(ORDER));
  assert.deepEqual(bad, []);
});

test("no component stylesheet puts rules outside a cap layer", () => {
  const bad = [];
  for (const f of cssFiles("components")) {
    const css = readFileSync(f, "utf8")
      .replace(/\/\*[\s\S]*?\*\//g, "")
      .replace(ORDER, "")
      // A stylesheet it builds on, a sibling component's (link.css takes link-file.css) or one of
      // its own parts (ambient.css takes each kind's file), checked here on its own.
      .replace(/^\s*@import "(?:\.\.\/([\w-]+)\/\1|\.\/[\w-]+)\.css";/gm, "")
      .trim();
    if (css && !/^@layer cap\.(components|base|utilities) \{/.test(css)) bad.push(f);
  }
  assert.deepEqual(bad, []);
});

// A scroll-driven animation needs animation-duration auto. Lightning CSS (Vite's minifier) folds an
// `animation` shorthand and its timeline into one shorthand with a 0s duration, which Chromium runs
// as finished: the table-scroll fades showed both ends at rest on dustinedwards.info's built CSS.
// Longhands with `animation-duration: auto` survive minifying; this checks the minified output.
test("every scroll-driven animation keeps duration auto after minifying", async () => {
  const { transform } = await import("lightningcss");
  const files = [...cssFiles("components"), "css/utilities.css"];
  const rules = files.flatMap((f) => {
    const out = transform({ filename: f, code: readFileSync(f), minify: true }).code.toString();
    // Each run of declarations between braces; nesting only splits a rule into more runs.
    return out
      .split(/[{}]/)
      .filter((body) => !body.startsWith("@"))
      .filter((body) => /animation(?:-timeline)?:[^;]*\b(?:scroll|view)\(/.test(body))
      .map((body) => [f, body]);
  });
  assert.ok(
    rules.length >= 3,
    "the scroll fades, the truncated label and the header fade are found",
  );
  const bad = rules.filter(([, body]) => !/animation-duration:auto(?![^;]*,)/.test(body));
  assert.deepEqual(bad, []);
});
