import assert from "node:assert/strict";
import { mkdirSync, mkdtempSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { test } from "node:test";
import { capsomerStylesheet, inlineCss } from "../../bin/build.mjs";

test("an import is read in place, a layered one inside its layer, a bare specifier from the file", () => {
  // Inside the package, so "capsomer/..." resolves as the package's own name, as it does from a site.
  mkdirSync("test-results", { recursive: true });
  const dir = mkdtempSync(join("test-results", "build-"));
  writeFileSync(join(dir, "part.css"), ".a { color: red; }");
  writeFileSync(
    join(dir, "main.css"),
    '@import "./part.css" layer(cap.components);\n@import "capsomer/layers.css";\n.b {}',
  );
  const css = inlineCss(join(dir, "main.css"));
  assert.match(css, /@layer cap\.components \{\n\.a \{ color: red; \}\n\}/);
  assert.match(css, /@layer cap\.reset, cap\.tokens/);
  assert.doesNotMatch(css, /@import/);
});

test("the stylesheet puts the family inside cap.tokens and the site's CSS last", () => {
  const css = capsomerStylesheet({
    family: "teal",
    parts: ["button"],
    fonts: false,
    after: [".site {}"],
  });
  assert.doesNotMatch(css, /@import/);
  assert.ok(css.indexOf("@layer cap.tokens {\n/* Generated by tokens/palette.mjs: the teal") > 0);
  assert.ok(css.indexOf(".cap-btn") > css.indexOf("teal"));
  assert.ok(css.endsWith(".site {}"));
});
